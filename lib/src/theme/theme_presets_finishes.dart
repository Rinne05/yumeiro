YumeiroSemanticVisualTheme _finishVisuals(
  YumeiroColorTokens colors,
  YumeiroRadiiTokens radii,
  YumeiroMotion motion,
  _Finish finish,
  Map<String, Object> parameters,
) => _variantVisuals(
  colors,
  radii,
  motion,
  destinationBackground: true,
  focus: YumeiroFocusIndicator(
    side: BorderSide(color: colors.accent, width: 2),
  ),
  pressedScale: finish == _Finish.silicone ? .97 : .985,
  paint: (role, value, states) {
    if (role == YumeiroSurfaceRole.canvas) {
      return value.copyWith(effects: YumeiroEffectStack.none);
    }
    // Artwork-overlay controls retain their own contrast-safe recipe.
    if (role == YumeiroControlRole.overlay) return value;
    final brightness = yumeiroRelativeLuminance(colors.background) < .18
        ? Brightness.dark
        : Brightness.light;
    final dark = brightness == Brightness.dark;
    final navigation = role == YumeiroSurfaceRole.navigation;
    final raised = _isRaisedSurface(role);
    final panel = role == YumeiroSurfaceRole.panel;
    final inset = role == YumeiroSurfaceRole.inset;
    final compact = role == YumeiroSurfaceRole.compact;
    final control = _isSolidControl(role);
    final active = _isActiveLightweight(role, states);
    if (!navigation &&
        !raised &&
        !panel &&
        !inset &&
        !compact &&
        !control &&
        !active) {
      return value.copyWith(effects: YumeiroEffectStack.none);
    }
    final pressed = states.contains(WidgetState.pressed);
    final action =
        role == YumeiroControlRole.primary || role == YumeiroControlRole.danger;
    final translucent =
        finish == _Finish.acrylic || finish == _Finish.frostedGlass;
    final floating =
        role == YumeiroSurfaceRole.floating ||
        role == YumeiroSurfaceRole.modal ||
        role == YumeiroSurfaceRole.toast;
    final shadow = navigation || inset
        ? 0.0
        : pressed
        ? .15
        : floating
        ? 1.25
        : panel || raised
        ? 1.0
        : .45;
    final highlight =
        _materialRatio(parameters, 'materialHighlight') * (pressed ? .55 : 1);
    // Base recipes supply selected/hover/pressed colors. Preserve them when
    // making an opaque finish, including translucent selection overlays.
    final color = yumeiroAlphaBlend(
      value.background,
      colors.surfaceSecondary,
    ).withValues(alpha: 1);
    // Dark palettes use a light semantic error color. Choose a dark ink for
    // the filled danger action while keeping error labels light on dark rows.
    if (dark && role == YumeiroControlRole.danger) {
      value = value.copyWith(
        foreground: yumeiroRelativeLuminance(color) > .18
            ? const Color(0xFF211016)
            : Colors.white,
      );
    }
    final material = switch (finish) {
      _Finish.ceramic => YumeiroMaterials.ceramic(
        color: color,
        brightness: brightness,
        highlight: highlight,
        shadow: shadow,
      ),
      _Finish.brushedMetal => YumeiroMaterials.brushedMetal(
        color: color,
        brightness: brightness,
        highlight: highlight,
        texture: _materialRatio(parameters, 'textureStrength'),
        shadow: shadow,
      ),
      _Finish.silicone => YumeiroMaterials.silicone(
        color: color,
        brightness: brightness,
        pressed: pressed || inset,
        highlight: highlight,
        shadow: shadow,
      ),
      _Finish.acrylic => YumeiroMaterials.acrylic(
        brightness: brightness,
        highlight: highlight,
        tint: color.withValues(
          alpha:
              ((floating
                          ? (dark ? .92 : .84)
                          : action
                          ? (dark ? .96 : .94)
                          : (dark ? .62 : .42)) *
                      _materialRatio(parameters, 'materialOpacity'))
                  .clamp(0, 1),
        ),
        blur: (parameters['materialBlur'] as double?) ?? 24,
        shadow: shadow,
      ),
      _Finish.frostedGlass => YumeiroMaterials.frostedGlass(
        brightness: brightness,
        tint: color.withValues(
          alpha:
              ((floating
                          ? (dark ? .9 : .80)
                          : action
                          ? (dark ? .96 : .94)
                          : (dark ? .48 : .30)) *
                      _materialRatio(parameters, 'materialOpacity'))
                  .clamp(0, 1),
        ),
        blur: (parameters['materialBlur'] as double?) ?? 24,
        thickness: 18 * _materialRatio(parameters, 'glassEdge'),
        highlight: highlight,
        shadow: shadow,
      ),
    };
    var result = material.applyTo(value);
    // Keep quiet inset capsules cheap and avoid stacking optical layers on
    // tiny passive badges. Interactive surfaces still receive the finish.
    if (translucent && (compact || inset)) {
      result = result.copyWith(effects: YumeiroEffectStack.none);
    }
    return result;
  },
);

YumeiroSwitchVisuals _finishSwitchVisualsBuilder(
  YumeiroColorTokens colors,
  YumeiroSemanticVisualTheme visuals,
) {
  YumeiroVisualAppearance track(Set<WidgetState> states) => visuals
      .control(
        states.contains(WidgetState.selected)
            ? YumeiroControlRole.primary
            : YumeiroControlRole.neutral,
        states,
      )
      .copyWith(shape: const StadiumBorder());
  YumeiroVisualAppearance thumb(Set<WidgetState> states) => visuals
      .control(
        YumeiroControlRole.secondary,
        states.difference(const {WidgetState.selected, WidgetState.focused}),
      )
      .copyWith(
        shape: const CircleBorder(),
        focusIndicator: YumeiroFocusIndicator.none,
      );
  return YumeiroSwitchVisuals(
    track: YumeiroVisualRecipe(
      base: track(const {}),
      states: WidgetStateProperty.resolveWith(track),
      focusIndicator: YumeiroFocusIndicator(
        side: BorderSide(color: colors.accent, width: 2),
      ),
    ),
    thumb: YumeiroVisualRecipe(
      base: thumb(const {}),
      states: WidgetStateProperty.resolveWith(thumb),
    ),
  );
}
